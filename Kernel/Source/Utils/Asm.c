typedef struct {
    UINT8 *Data;
    USIZE Size;
    USIZE Capacity;
    UINT64 Vaddr;
    UINT64 MemSize;     // for .bss
    UINT8  Kind;
    CHAR   Name[16];
} AsmSec;

typedef struct {
    CHAR   Name[ASM_MAX_NAME_LEN];
    UINT32 Section;
    UINT64 Offset;
    BOOL   Global;
    BOOL   Defined;
    BOOL   IsConstant;          // TRUE — this is a constant
    UINT64 ConstValue;          // computed value
    BOOL   IsExpr;              // TRUE — value not yet computed (has Expr)
    CHAR   Expr[128];           // expression text for deferred evaluation
} AsmSym;

typedef enum {
    OPK_NONE = 0,
    OPK_REG,
    OPK_IMM,
    OPK_MEM,
    OPK_LABEL,
    OPK_SIZEPREFIX,
} OpKind;

typedef struct {
    OpKind Kind;
    UINT8  Reg;         // 0..15 (rax..r15), 16..23 (al..r15b), ...
    UINT8  RegSize;     // 1,2,4,8
    UINT64 Imm;
    CHAR   Label[ASM_MAX_NAME_LEN];
    // Memory
    UINT8  MemBase;
    UINT8  MemIndex;
    UINT8  MemScale;
    INT32  MemDisp;
    CHAR   MemDispLabel[ASM_MAX_NAME_LEN];
    BOOL   MemRipRel;
    // Size prefix
    UINT8  Size;
} AsmOp;

typedef struct {
    UINT32 Line;
    CHAR   Mnemonic[16];
    AsmOp  Op[3];
    UINT8  OpCount;
} AsmInsn;

typedef struct {
    AsmSec  Sections[ASM_MAX_SECTIONS];
    UINT32  SectionCount;
    AsmSym  Symbols[ASM_MAX_SYMBOLS];
    UINT32  SymbolCount;
    AsmInsn Insns[ASM_MAX_INSTRUCTIONS];
    UINT32  InsnCount;
    UINT32  InsnSec[ASM_MAX_INSTRUCTIONS];
    UINT32  CurrentSection;
    CHAR    LastGlobal[ASM_MAX_NAME_LEN];

    // Data generated by encode
    UINT8  *CodeBuf;      // buffer for .text code
    USIZE   CodeSize;
    USIZE   CodeCap;

    // For call/jmp relocations: offsets in CodeBuf where rel32 is written
    struct {
        UINT32 Offset;
        CHAR   Label[ASM_MAX_NAME_LEN];
    } Relocs[ASM_MAX_INSTRUCTIONS];
    UINT32 RelocCount;

    // Data patches (.data) for references via [rel ...]
    struct {
        UINT32 Offset;
        CHAR   Label[ASM_MAX_NAME_LEN];
    } DataRelocs[ASM_MAX_INSTRUCTIONS];
    UINT32 DataRelocCount;

    UINT64 Entry;
    BOOL   HasEntry;

    BOOL   Error;
    CHAR   ErrMsg[256];
    UINT32 ErrLine;
} AsmCtx;

